import test from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, cpSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import { join, resolve } from "node:path";
import { tmpdir } from "node:os";
import { initCliTable } from "../src/plugin/init.mjs";
import { validateCliTable } from "../packages/sfd-plugin/validate.mjs";

test("generator maps manifest flags, records reviews, filters operations and writes package metadata", async t => {
  const root = mkdtempSync(join(tmpdir(), "sfd-init-"));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  cpSync(resolve("test/fixtures/plugins/echo"), root, { recursive: true });
  const { table, review } = await initCliTable(root, { ops: ["echo.say"], write: true });
  assert.deepEqual(validateCliTable(table), []);
  const command = table.commands[0];
  assert.deepEqual(command.name, ["echo", "say"]);
  assert.deepEqual(command.sf, ["echo", "say"]);
  assert.deepEqual(command.flags.find(f => f.name === "text"), { name: "text", type: "string", char: "t", required: true, option: "text" });
  assert.equal(command.flags.find(f => f.name === "loud").type, "boolean");
  assert.equal(command.flags.find(f => f.name === "tag").multiple, true);
  assert.ok(!command.flags.some(f => f.name === "json"));
  assert.equal(command.flags.find(f => f.name === "target-org").option, undefined);
  assert.match(review.join("\n"), /relationships/);
  assert.match(review.join("\n"), /tighten agentTip/);
  assert.equal(JSON.parse(readFileSync(join(root, "package.json"))).sfd.cli, "./cli.json");
  assert.deepEqual(JSON.parse(readFileSync(join(root, "cli.json"))), table);
  assert.ok(readFileSync(join(root, "package.json"), "utf8").endsWith("\n"));
  await assert.rejects(initCliTable(root, { ops: ["echo.unknown"] }), /Unknown operation/);
  const manifest = JSON.parse(readFileSync(join(root, "oclif.manifest.json")));
  manifest.commands["echo:say"].flags.mystery = { type: "integer", parse: "custom" };
  writeFileSync(join(root, "oclif.manifest.json"), JSON.stringify(manifest));
  const unmapped = await initCliTable(root, { ops: ["echo.say"] });
  assert.match(unmapped.review.join("\n"), /--mystery has no option key/);
  assert.match(unmapped.review.join("\n"), /custom parse function/);
  assert.equal(unmapped.table.commands[0].flags.find(f => f.name === "mystery").type, "integer");
  rmSync(join(root, "oclif.manifest.json"));
  const fallback = await initCliTable(root, { ops: ["echo.say"] });
  assert.match(fallback.review.join("\n"), /run your build/);
  assert.equal(fallback.table.commands[0].flags[0].option, "text");
});
